    // 1. chr-массивы: [char]0x68+1, chr(112), (char)115, String.fromCharCode(97,98),
    //    PowerShell: ( 72,101,... | ForEach-Object {[char]$_} )
    static string DecodeCharArrays(string input, ref bool changed) {
        bool ch = false;
        var chrRe = new Regex(@"\[?char\]?\(?\s*(0x[0-9a-fA-F]+|\d{1,3})\s*([+\-]\d{1,3})?\s*\)?", RegexOptions.NonBacktracking);
        string r1 = chrRe.Replace(input, m => {
            try {
                int code = m.Groups[1].Value.StartsWith("0x", StringComparison.OrdinalIgnoreCase)
                    ? Convert.ToInt32(m.Groups[1].Value, 16) : int.Parse(m.Groups[1].Value);
                if (m.Groups[2].Success) code += int.Parse(m.Groups[2].Value);
                if (code >= 32 && code < 127) { ch = true; return ((char)code).ToString(); }
            } catch { }
            return m.Value;
        });
        var fcc = new Regex(@"String\.fromCharCode\(([^)]{20,})\)", RegexOptions.NonBacktracking);
        string r2 = fcc.Replace(r1, m => {
            try {
                var sb = new StringBuilder();
                foreach (var part in m.Groups[1].Value.Split(',')) {
                    string v = part.Trim();
                    if (v.Length == 0) continue;
                    int code = v.StartsWith("0x", StringComparison.OrdinalIgnoreCase) ? Convert.ToInt32(v, 16) : int.Parse(v);
                    if (code < 32 || code >= 127) return m.Value;
                    sb.Append((char)code);
                }
                if (sb.Length >= 4) { ch = true; return "\"" + sb + "\""; }
            } catch { }
            return m.Value;
        });
        // PowerShell-пайплайн кодов символов
        var psArr = new Regex(@"\(\s*((?:\d{1,3}\s*,\s*){23,}\d{1,3})\s*\|\s*ForEach-Object\s*\{?\s*\[char\]", RegexOptions.NonBacktracking);
        string r3 = psArr.Replace(r2, m => {
            try {
                var sb = new StringBuilder();
                foreach (var part in m.Groups[1].Value.Split(',')) {
                    int code = int.Parse(part.Trim());
                    if (code < 32 || code >= 127) return m.Value;
                    sb.Append((char)code);
                }
                string dec = sb.ToString();
                if (dec.Length >= 8 && Readability(dec) >= 60) { ch = true; return "\"" + dec + "\""; }
            } catch { }
            return m.Value;
        });
        if (ch) changed = true;
        return r3;
    }

    // 2. Python/JS: "\\x68\\x65\\x6c..." внутри exec/eval/iex — снимаем эскейпы
    static string DecodeInlineHexEscapes(string input, ref bool changed) {
        bool ch = false;
        // без backreference: NonBacktracking (RE2) их не поддерживает
        var re = new Regex(@"(?i)(?:exec|eval|iex)\s*\(\s*(""|')((?:\\x[0-9a-f]{2}){10,})(""|')", RegexOptions.NonBacktracking);
        string r = re.Replace(input, m => {
            try {
                string body = m.Groups[2].Value;
                var bytes = new byte[body.Length / 4];
                for (int i = 0; i < bytes.Length; i++) bytes[i] = Convert.ToByte(body.Substring(i * 4 + 2, 2), 16);
                string dec = Encoding.UTF8.GetString(bytes);
                if (dec.Length >= 8 && Readability(dec) >= 60) { ch = true; return "\"" + dec + "\""; }
            } catch { }
            return m.Value;
        });
        if (ch) changed = true;
        return r;
    }

    // 3. base64-блобы: стандарт + URL-safe (по одному слою за проход, рекурсия снимет остальные)
    static string DecodeBase64Blobs(string input, ref bool changed) {
        var b64 = new Regex(@"[A-Za-z0-9+/]{40,}={0,2}", RegexOptions.NonBacktracking);
        foreach (Match m in b64.Matches(input)) {
            string dec = TryDecodeB64Layer(m.Value, false);
            if (dec != null) { changed = true; return input.Replace(m.Value, "\"" + dec + "\""); }
        }
        var b64u = new Regex(@"[A-Za-z0-9_-]{40,}", RegexOptions.NonBacktracking);
        foreach (Match m in b64u.Matches(input)) {
            string dec = TryDecodeB64Layer(m.Value, true);
            if (dec != null) { changed = true; return input.Replace(m.Value, "\"" + dec + "\""); }
        }
        return input;
    }

    static string TryDecodeB64Layer(string s, bool urlSafe) {
        try {
            string t = s;
            if (urlSafe) t = t.Replace('-', '+').Replace('_', '/');
            int pad = (4 - t.Length % 4) % 4;
            if (pad > 0) t += new string('=', pad);
            var bytes = Convert.FromBase64String(t);
            string txt = TryDecompressOrText(bytes);
            if (txt != null && txt.Length >= 12 && Readability(txt) >= 55) return txt;
        } catch { }
        return null;
    }

    // 4. hex-литералы: bytes.fromhex("..."), [Convert]::FromHexString("..."), int.fromhex
    static string DecodeHexLiterals(string input, ref bool changed) {
        bool ch = false;
        var re = new Regex(@"(?i)(?:fromhexstring|fromhexstr|fromhex)\s*\(\s*(""|')([0-9a-f]{40,})(""|')", RegexOptions.NonBacktracking);
        string r = re.Replace(input, m => {
            try {
                var bytes = Convert.FromHexString(m.Groups[2].Value);
                string dec = TryDecompressOrText(bytes);
                if (dec != null && dec.Length >= 12 && Readability(dec) >= 55) { ch = true; return "\"" + dec + "\""; }
            } catch { }
            return m.Value;
        });
        if (ch) changed = true;
        return r;
    }

    // 5. PowerShell byte-массивы: [byte[]]@(72,101,108,...) — напрямую или XOR с ключом
    static string DecodeByteArrayLiterals(string input, ref bool changed) {
        bool ch = false;
        var re = new Regex(@"\[byte\[\]\]\s*@\(\s*((?:\d{1,3}\s*,\s*){23,}\d{1,3})\s*\)", RegexOptions.NonBacktracking);
        string r = re.Replace(input, m => {
            try {
                var nums = new List<byte>();
                foreach (var part in m.Groups[1].Value.Split(',')) {
                    int v = int.Parse(part.Trim());
                    if (v < 0 || v > 255) return m.Value;
                    nums.Add((byte)v);
                }
                var bytes = nums.ToArray();
                string direct = TryDecompressOrText(bytes);
                if (direct != null && direct.Length >= 12 && Readability(direct) >= 60) {
                    ch = true; return "\"" + direct + "\"";
                }
                foreach (var k in FindXorKeys(input)) {
                    var dec = XorBytes(bytes, k);
                    string t = TryDecompressOrText(dec);
                    if (t != null && t.Length >= 12 && Readability(t) >= 60) { ch = true; return "\"" + t + "\""; }
                }
            } catch { }
            return m.Value;
        });
        if (ch) changed = true;
        return r;
    }

    // Поиск ключей XOR в тексте скрипта: литералы (0x42, 66, -bxor, $k = 0x42)
    // и многобайтные [byte[]]@(1,2,3,4) / $key = @(1,2,3,4)
    static List<byte[]> FindXorKeys(string text) {
        var keys = new List<byte[]>();
        var seen = new HashSet<string>();
        foreach (Match m in Regex.Matches(text, @"(?i)(?:-bxor|\^|xor)\s*(0x[0-9a-f]{1,2}|\d{1,3})\b", RegexOptions.NonBacktracking)) {
            try {
                string v = m.Groups[1].Value;
                int k = v.StartsWith("0x", StringComparison.OrdinalIgnoreCase) ? Convert.ToInt32(v, 16) : int.Parse(v);
                if (k >= 0 && k < 256 && seen.Add("1:" + k)) keys.Add(new byte[] { (byte)k });
            } catch { }
        }
        foreach (Match m in Regex.Matches(text, @"(?i)\$[a-z_]+\s*=\s*(0x[0-9a-f]{1,2}|\d{1,3})\s*[;\n]", RegexOptions.NonBacktracking)) {
            try {
                string v = m.Groups[1].Value;
                int k = v.StartsWith("0x", StringComparison.OrdinalIgnoreCase) ? Convert.ToInt32(v, 16) : int.Parse(v);
                if (k >= 0 && k < 256 && seen.Add("1:" + k)) keys.Add(new byte[] { (byte)k });
            } catch { }
        }
        foreach (Match m in Regex.Matches(text, @"(?i)(?:\$[a-z_]+\s*=\s*)?\[?byte\[\]\]?\s*@\(\s*((?:\d{1,3}\s*,\s*){1,15}\d{1,3})\s*\)", RegexOptions.NonBacktracking)) {
            try {
                var arr = new List<byte>();
                foreach (var part in m.Groups[1].Value.Split(',')) {
                    int v = int.Parse(part.Trim());
                    if (v < 0 || v > 255) { arr = null; break; }
                    arr.Add((byte)v);
                }
                if (arr != null && arr.Count >= 2 && arr.Count <= 16 && seen.Add("n:" + string.Join(",", arr)))
                    keys.Add(arr.ToArray());
            } catch { }
        }
        return keys;
    }

    // 6. XOR-пейлоады: base64-блоб + ключ-литерал из скрипта; без ключа — перебор
    static string DecodeXorPayloads(string input, ref bool changed) {
        var keys = FindXorKeys(input);
        var b64 = new Regex(@"[A-Za-z0-9+/]{40,}={0,2}", RegexOptions.NonBacktracking);
        foreach (Match m in b64.Matches(input)) {
            byte[] bytes;
            try { bytes = Convert.FromBase64String(m.Value); } catch { continue; }
            if (bytes.Length < 16) continue;
            foreach (var k in keys) {
                var dec = XorBytes(bytes, k);
                string t = TryDecompressOrText(dec);
                if (t != null && t.Length >= 12 && Readability(t) >= 60) {
                    changed = true; return input.Replace(m.Value, "\"" + t + "\"");
                }
            }
            // перебор одиночного байта (длинные блобы, ключ вычисляется в рантайме)
            if (bytes.Length >= 32 && bytes.Length <= 2_000_000) {
                var brute = BruteSingleXor(bytes);
                if (brute != null) {
                    string t = TryDecompressOrText(brute);
                    if (t != null && t.Length >= 12 && Readability(t) >= 62) {
                        changed = true; return input.Replace(m.Value, "\"" + t + "\"");
                    }
                }
                if (bytes.Length >= 64 && bytes.Length <= 2_000_000) {
                    var mx = TryMultiXor(bytes);
                    if (mx != null) {
                        string t = TryDecompressOrText(mx);
                        if (t != null && t.Length >= 12 && Readability(t) >= 62) {
                            changed = true; return input.Replace(m.Value, "\"" + t + "\"");
                        }
                    }
                }
            }
        }
        return input;
    }

    static byte[] XorBytes(byte[] bytes, byte[] key) {
        var res = new byte[bytes.Length];
        for (int i = 0; i < bytes.Length; i++) res[i] = (byte)(bytes[i] ^ key[i % key.Length]);
        return res;
    }

    static byte[] BruteSingleXor(byte[] bytes) {
        byte[] best = null; double bestScore = 0;
        var tmp = new byte[bytes.Length];
        for (int k = 1; k < 256; k++) {
            for (int i = 0; i < bytes.Length; i++) tmp[i] = (byte)(bytes[i] ^ k);
            double r = Readability(tmp);
            if (r > bestScore) { bestScore = r; best = (byte[])tmp.Clone(); }
        }
        return bestScore >= 62 ? best : null;
    }

    // Многобайтный XOR (cryptopals set 1 ch.6): длина ключа через Hamming distance,
    // транспонирование по позициям, посимвольный подбор ключа частотным анализом.
    static byte[] TryMultiXor(byte[] bytes) {
        int bestLen = 1; double bestDist = double.MaxValue;
        for (int len = 2; len <= 4; len++) {
            double dist = 0; int pairs = 0;
            for (int i = 0; i + 2 * len <= bytes.Length && pairs < 16; i += len) {
                dist += Hamming(bytes, i, i + len, len); pairs++;
            }
            if (pairs > 0) {
                double norm = dist / pairs / len;
                if (norm < bestDist) { bestDist = norm; bestLen = len; }
            }
        }
        if (bestLen < 2) return null;
        var key = new byte[bestLen];
        for (int j = 0; j < bestLen; j++) {
            var col = new byte[(bytes.Length - j + bestLen - 1) / bestLen];
            int n = 0;
            for (int i = j; i < bytes.Length; i += bestLen) col[n++] = bytes[i];
            byte bestKey = 0; double bestScore = 0;
            var tmp = new byte[col.Length];
            for (int k = 1; k < 256; k++) {
                for (int i = 0; i < col.Length; i++) tmp[i] = (byte)(col[i] ^ k);
                double r = Readability(tmp);
                if (r > bestScore) { bestScore = r; bestKey = (byte)k; }
            }
            if (bestScore < 40) return null;
            key[j] = bestKey;
        }
        var dec = XorBytes(bytes, key);
        return Readability(dec) >= 62 ? dec : null;
    }

    static double Hamming(byte[] b, int a, int c, int len) {
        int diff = 0;
        for (int i = 0; i < len; i++) {
            byte x = (byte)(b[a + i] ^ b[c + i]);
            while (x != 0) { diff += x & 1; x >>= 1; }
        }
        return diff;
    }

    // 7. Реверс строк: "...\"[::-1], \"...\".split('').reverse().join('')
    static string DecodeReversedStrings(string input, ref bool changed) {
        bool ch = false;
        var re = new Regex(@"(""|')([^""']{16,})(""|')\s*\[\s*::\s*-1\s*\]", RegexOptions.NonBacktracking);
        string r1 = re.Replace(input, m => {
            string dec = ReverseStr(m.Groups[2].Value);
            if (Readability(dec) >= 60) { ch = true; return "\"" + dec + "\""; }
            return m.Value;
        });
        var re2 = new Regex(@"(""|')([^""']{16,})(""|')\s*\.split\s*\(\s*[""']?[""']?\s*\)\s*\.reverse\s*\(\s*\)\s*\.join\s*\(\s*[""']?[""']?\s*\)", RegexOptions.NonBacktracking);
        string r2 = re2.Replace(r1, m => {
            string dec = ReverseStr(m.Groups[2].Value);
            if (Readability(dec) >= 60) { ch = true; return "\"" + dec + "\""; }
            return m.Value;
        });
        if (ch) changed = true;
        return r2;
    }
    static string ReverseStr(string s) {
        var arr = s.ToCharArray(); Array.Reverse(arr); return new string(arr);
    }

    // 8. ROT13/ROTn: пробуем все сдвиги; принимаем, если появился маркер
    // опасности, которого НЕ было в исходнике (JS eval-обфускация), или
    // читаемость заметно выросла.
    static string DecodeRotShifts(string input, ref bool changed) {
        if (input.Length > 512 * 1024) return input;
        double origRead = Readability(input);
        string best = null; double bestScore = 0;
        for (int shift = 1; shift < 26; shift++) {
            string cand = CaesarShift(input, shift);
            double r = Readability(cand);
            if (r >= 65 && HasNewMarker(cand, input)) { changed = true; return cand; }
            if (r > bestScore) { bestScore = r; best = cand; }
        }
        if (best != null && bestScore >= 65 && bestScore > origRead + 10) { changed = true; return best; }
        return input;
    }
    // Поиск токена с границей слова слева: "eval(" в "model.eval()" не считается
    // ('.' тоже блокирует — вызов метода объекта)
    static bool ContainsToken(string text, string token) {
        int idx = 0;
        while ((idx = text.IndexOf(token, idx, StringComparison.Ordinal)) >= 0) {
            bool leftOk = idx == 0 || !(char.IsLetterOrDigit(text[idx - 1]) || text[idx - 1] == '_' || text[idx - 1] == '.');
            if (leftOk) return true;
            idx += token.Length;
        }
        return false;
    }

    static bool HasNewMarker(string decoded, string original) {
        foreach (var m in DEOBF_MARKERS) {
            // обёрточные маркеры (eval(/exec(/iex() появляются и в обратном
            // сдвиге обёртки — они не доказывают декод содержимого
            if (m.Equals("eval(", StringComparison.OrdinalIgnoreCase)
                || m.Equals("exec(", StringComparison.OrdinalIgnoreCase)
                || m.Equals("iex(", StringComparison.OrdinalIgnoreCase)) continue;
            if (decoded.IndexOf(m, StringComparison.OrdinalIgnoreCase) >= 0
                && original.IndexOf(m, StringComparison.OrdinalIgnoreCase) < 0) return true;
        }
        return false;
    }
    static string CaesarShift(string s, int shift) {
        var sb = new StringBuilder(s.Length);
        foreach (char c in s) {
            if (c >= 'a' && c <= 'z') sb.Append((char)('a' + (c - 'a' + shift) % 26));
            else if (c >= 'A' && c <= 'Z') sb.Append((char)('A' + (c - 'A' + shift) % 26));
            else sb.Append(c);
        }
        return sb.ToString();
    }

    // gzip (1F 8B) / zlib-deflate (78 01/9C/DA) / brotli (0B 02) разжатие, иначе UTF-8 текст
    static string TryDecompressOrText(byte[] bytes) {
        try {
            if (bytes.Length > 2 && bytes[0] == 0x1F && bytes[1] == 0x8B) {
                using var ms = new MemoryStream(bytes);
                using var gz = new System.IO.Compression.GZipStream(ms, System.IO.Compression.CompressionMode.Decompress);
                using var outMs = new MemoryStream();
                gz.CopyTo(outMs);
                if (outMs.Length > 0 && outMs.Length < 4_000_000) return Encoding.UTF8.GetString(outMs.ToArray());
                return null;
            }
            if (bytes.Length > 2 && bytes[0] == 0x78 && (bytes[1] == 0x01 || bytes[1] == 0x9C || bytes[1] == 0xDA)) {
                // zlib: 2-байтовый заголовок + raw deflate (DeflateStream не понимает zlib-обёртку)
                using var ms = new MemoryStream(bytes, 2, bytes.Length - 2);
                using var ds = new System.IO.Compression.DeflateStream(ms, System.IO.Compression.CompressionMode.Decompress);
                using var outMs = new MemoryStream();
                ds.CopyTo(outMs);
                if (outMs.Length > 0 && outMs.Length < 4_000_000) return Encoding.UTF8.GetString(outMs.ToArray());
                return null;
            }
            if (bytes.Length > 2 && bytes[0] == 0x0B && bytes[1] == 0x02) {
                using var ms = new MemoryStream(bytes);
                using var bs = new System.IO.Compression.BrotliStream(ms, System.IO.Compression.CompressionMode.Decompress);
                using var outMs = new MemoryStream();
                bs.CopyTo(outMs);
                if (outMs.Length > 0 && outMs.Length < 4_000_000) return Encoding.UTF8.GetString(outMs.ToArray());
                return null;
            }
            if (Encoding.UTF8.GetString(bytes) is var s && s.Length >= 12) return s;
        } catch { }
        return null;
    }

    static void AnalyzeScript(ScanResult res, string path, byte[] data) {
        // UTF-16 (BOM FF FE / FE FF) и Windows-1251 для .bat/.cmd: иначе mojibake
        string text;
        if (data.Length >= 2 && data[0] == 0xFF && data[1] == 0xFE) text = Encoding.Unicode.GetString(data, 2, data.Length - 2);
        else if (data.Length >= 2 && data[0] == 0xFE && data[1] == 0xFF) text = Encoding.BigEndianUnicode.GetString(data, 2, data.Length - 2);
        else if (data.Length >= 3 && data[0] == 0xEF && data[1] == 0xBB && data[2] == 0xBF) text = Encoding.UTF8.GetString(data, 3, data.Length - 3);
        else if (Path.GetExtension(path).ToLowerInvariant() is ".bat" or ".cmd") text = DecodeCp1251(data);
        else text = Encoding.UTF8.GetString(data);
        string lower = text.ToLowerInvariant();

        // Плотность hex-escape-последовательностей — маркер обфускации
        int hexEscapes = Regex.Matches(lower, @"\\x[0-9a-f]{2}", RegexOptions.NonBacktracking).Count;
        if (hexEscapes > 40) Add(res, "obfuscated", "много hex-escape последовательностей (" + hexEscapes + ") — обфускация", 8, "hex_escape", res.File);

        int charCodes = Regex.Matches(lower, @"[\[\(]?char\(?\s*\d{1,3}\s*\)", RegexOptions.NonBacktracking).Count;
        if (charCodes > 20) Add(res, "obfuscated", "массовая сборка строк из кодов символов", 8, "charcode", res.File);

        // Реверс строк — без Split('\n') на весь файл (OOM на 8 МБ переводов строк):
        // считаем посимвольно вхождения маркеров
        int reversed = 0;
        int idxRev = 0;
        while ((idxRev = lower.IndexOf("::-1]", idxRev, StringComparison.Ordinal)) >= 0 && reversed < 4) { reversed++; idxRev += 6; }
        if (lower.IndexOf("-join", StringComparison.Ordinal) >= 0 || lower.IndexOf("::join", StringComparison.Ordinal) >= 0) reversed++;
        if (reversed > 3) Add(res, "obfuscated", "реверс строк — типичный приём обфускации", 6, "reverse_str", res.File);

        // Много длинных строк без пробелов (обфускация идентификаторов) — через IndexOf, без массива
        int longTight = 0, lineStart = 0;
        while (lineStart < text.Length && longTight <= 12) {
            int nl = text.IndexOf('\n', lineStart);
            if (nl < 0) nl = text.Length;
            int len = nl - lineStart;
            if (len > 120) {
                bool hasSpace = false;
                for (int i = lineStart; i < nl; i++) { if (text[i] == ' ') { hasSpace = true; break; } }
                if (!hasSpace) longTight++;
            }
            lineStart = nl + 1;
        }
        if (longTight > 8) Add(res, "obfuscated", "много длинных однострочных конструкций без пробелов", 6, "tight_lines", res.File);

        // b64_script вес снижен: «import base64» есть у легальных скриптов (PNG-картинки, токены)
        if (lower.Contains("base64") || lower.Contains("b64decode") || lower.Contains("frombase64"))
            Add(res, "obfuscated", "base64-кодирование в скрипте", 2, "b64_script", res.File);

        // ---- Деобфускация: снимаем слои и прогоняем правила по расшифрованному тексту ----
        // Запускаем, когда есть маркеры обфускации ИЛИ скрипт достаточно мал (ROT-обфускация
