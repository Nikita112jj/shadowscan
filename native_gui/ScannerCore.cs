    class SectionInfo { public string Name; public uint VirtualSize, VirtualAddress, RawSize, RawPtr, Characteristics; public double Entropy; }

    static HashSet<string> ParsePe(ScanResult res, byte[] d, bool isDotnet) {
        uint peOff = BitConverter.ToUInt32(d, 0x3C);
        if (peOff + 4 >= d.Length || d[peOff] != 0x50 || d[peOff+1] != 0x45) throw new Exception("no PE");
        ushort nSections = BitConverter.ToUInt16(d, (int)peOff + 6);
        ushort optSize = BitConverter.ToUInt16(d, (int)peOff + 20);
        ushort magic = BitConverter.ToUInt16(d, (int)peOff + 24);
        bool pe32 = magic == 0x10B;
        if (magic != 0x10B && magic != 0x20B) throw new Exception("bad optional magic");
        var imports = new HashSet<string>();

        // Data directories: для PE32 — смещение 96, для PE32+ (x64) — 112
        int optBase = (int)peOff + 24;
        int ddBase = optBase + (pe32 ? 96 : 112);
        uint comRva = BitConverter.ToUInt32(d, ddBase + 14*8);
        uint tlsRva = BitConverter.ToUInt32(d, ddBase + 9*8);

        // Секции
        int secBase = (int)peOff + 24 + optSize;
        var sections = new List<SectionInfo>();
        for (int i = 0; i < nSections; i++) {
            int off = secBase + i * 40;
            if (off + 40 > d.Length) break;
            var name = Encoding.ASCII.GetString(d, off, 8).TrimEnd('\0');
            uint vsize = BitConverter.ToUInt32(d, off + 8);
            uint va = BitConverter.ToUInt32(d, off + 12);
            uint rawSize = BitConverter.ToUInt32(d, off + 16);
            uint rawPtr = BitConverter.ToUInt32(d, off + 20);
            uint chars = BitConverter.ToUInt32(d, off + 36);
            double ent = 0;
            if (rawSize > 0 && rawPtr + rawSize <= d.Length) {
                int len = (int)Math.Min(rawSize, 4 * 1024 * 1024);
                ent = Entropy(d, (int)rawPtr, len);
            }
            sections.Add(new SectionInfo { Name = name, VirtualSize = vsize, VirtualAddress = va, RawSize = rawSize, RawPtr = rawPtr, Characteristics = chars, Entropy = ent });
        }

        if (nSections == 0) Add(res, "format", "PE без секций", 6, "pe_nosec", res.File);
        // порог 15: Delphi/C++Builder и Tesseract легально имеют 8-19 секций
        if (nSections > 15) Add(res, "packed", "аномально много секций (" + nSections + ")", 4, "pe_manysec", res.File);

        // .NET-детект: COM descriptor должен указывать на валидный COR20-заголовок
        // (magic 0x48 0x02), иначе это мусор/иное использование data directory.
        if (comRva != 0) {
            int clrOff = RvaToOff(d, comRva, sections);
            if (clrOff < 0 || clrOff + 4 > d.Length || d[clrOff] != 0x48 || d[clrOff + 1] != 0x02) comRva = 0;
        }
        if (comRva != 0 && !isDotnet) Add(res, "dotnet", "CLR-заголовок в неожиданном месте", 5, "pe_com", res.File);
        if (tlsRva != 0) {
            // TLS-каталог есть у каждого C++/Rust/Go с thread_local — штрафуем только колбэки
            int tlsOff = RvaToOff(d, tlsRva, sections);
            // AddressOfCallBacks — смещение 12 в IMAGE_TLS_DIRECTORY (PE32), 24 (PE32+)
            int cbOffField = tlsOff + (pe32 ? 12 : 24);
            if (cbOffField + 4 <= d.Length) {
                uint cbRva = BitConverter.ToUInt32(d, cbOffField);
                if (cbRva != 0) Add(res, "evasion", "TLS-колбэки (скрытый запуск кода)", 1, "pe_tls", res.File);
            }
        }

        // NativeAOT-маркер: секция hydrated — высокая энтропия кода и отсутствие raw — норма
        bool isNativeAot = sections.Any(s => s.Name.Equals("hydrated", StringComparison.OrdinalIgnoreCase));
        if (isNativeAot)
            res.Findings.Add(new Finding { Severity = "info", Category = "format", Rule = "nativeaot",
                Detail = "NativeAOT-сборка (нативная компиляция .NET): высокая энтропия кода — норма" });
        foreach (var sec in sections) {
            string sn = sec.Name;
            // .ndata без raw — BSS-стиль легальных приложений (напр. ELEFANT AI),
            // у Enigma Protector .ndata всегда содержит raw-данные
            bool ndataBss = sn.Equals(".ndata", StringComparison.OrdinalIgnoreCase) && sec.RawSize == 0;
            foreach (var bad in PE_SUS_SECTIONS)
                if (!ndataBss && sn.Equals(bad, StringComparison.OrdinalIgnoreCase)) Add(res, "packed", "секция упаковщика: " + sn, 8, "packer_section", sn);
            // hydrated без raw — особенность NativeAOT; .bss — стандарт GCC/MinGW
            // (Git, Tesseract); .imrsiv — защитная секция taskmgr; .ndata без raw — BSS
            if (sec.VirtualSize > 0 && sec.RawSize == 0 && !ndataBss
                && !sn.Equals("hydrated", StringComparison.OrdinalIgnoreCase)
                && !sn.Equals(".bss", StringComparison.OrdinalIgnoreCase)
                && !sn.Equals(".imrsiv", StringComparison.OrdinalIgnoreCase))
                Add(res, "packed", "секция без raw-данных (упаковка): " + sn, 6, "packer_noraw", sn);
            // .rsrc/.reloc/.pdata — шумные у легитимных файлов
            if (sn.Equals(".rsrc", StringComparison.OrdinalIgnoreCase)
                || sn.Equals(".reloc", StringComparison.OrdinalIgnoreCase)
                || sn.Equals(".pdata", StringComparison.OrdinalIgnoreCase)) continue;
            if (sec.Entropy > 7.2) Add(res, "packed", "высокая энтропия секции " + sn + " (" + sec.Entropy.ToString("0.00") + ") — упаковка/шифрование", 6, "high_entropy", sn);
            else if (sec.Entropy > 6.5 && !isNativeAot
                     && !sn.Equals(".text", StringComparison.OrdinalIgnoreCase)
                     && !sn.Equals(".rdata", StringComparison.OrdinalIgnoreCase))
                Add(res, "packed", "повышенная энтропия секции " + sn + " (" + sec.Entropy.ToString("0.00") + ")", 3, "mid_entropy", sn);
        }

        // Энтропия всего файла. Большие файлы (> 20 МБ) — обычно легитимные бандлы
        // (PyInstaller, Electron, инсталляторы): они тоже "зашифрованы", но это норма.
        // Энтропия анализируемого буфера. Файлы >20 МБ (PyInstaller/Electron бандлы)
        // почти всегда «зашифрованы» легитимно — без доп. признаков не флагаем.
        double fileEnt = Entropy(d, 0, d.Length);
        if (fileEnt > 7.4 && res.Size > 64 * 1024 && res.Size < 20 * 1024 * 1024)
            Add(res, "packed", "энтропия файла " + fileEnt.ToString("0.00") + " — вероятно зашифрован", 7, "file_entropy", res.File);

        // Импорты
        try {
            uint importRva = BitConverter.ToUInt32(d, ddBase + 1*8);
            uint iatRva = BitConverter.ToUInt32(d, ddBase + 12*8);
            if (importRva != 0) ParseImports(d, importRva, sections, imports, pe32);
            // Для .NET импорты почти всегда скрыты в метаданных (нет классической таблицы) — не штрафуем.
            // IAT без import-директории — легитимная особенность (напр. System32), не упаковка.
            if (imports.Count == 0 && !isDotnet && importRva == 0 && iatRva == 0)
                Add(res, "packed", "импорты отсутствуют или скрыты (упаковка)", 5, "no_imports", res.File);
            ApplyImportRules(res, imports);
            // VM-протекторы (VMProtect/Themida/Enigma) и PIC-код (CF-исследование)
            CheckVmProtection(res, d, imports);
        } catch { /* импорты опциональны */ }

        // Overlay. Большие хвосты — норма для самораспаковывающихся бандлов
        // (PyInstaller и т.п.). Подозрительно, только когда файл маленький,
        // а overlay заметно больше самого кода (дописанный конфиг/полезная нагрузка).
        uint maxRawEnd = 0;
        foreach (var s in sections) maxRawEnd = Math.Max(maxRawEnd, s.RawPtr + s.RawSize);
        if (maxRawEnd > 0 && d.Length < 10 * 1024 * 1024 && d.Length > maxRawEnd + 1024
            && (d.Length - maxRawEnd) * 2 > maxRawEnd)
            Add(res, "packed", "overlay-данные после секций (" + (d.Length - maxRawEnd) + " байт)", 4, "overlay", res.File);
        return imports;
    }

    // Нормализация имён импортов: снимаем суффикс A/W (ANSI/Unicode-варианты одного API)
    static string NormApi(string s) {
        if (s.Length > 1 && (s[s.Length - 1] == 'A' || s[s.Length - 1] == 'W'))
            return s.Substring(0, s.Length - 1);
        return s;
    }

    // Вредоносные цепочки импортов (CHAIN_RULES): срабатывает только ПОЛНАЯ
    // комбинация групп + обязательный строковый контекст. Итог — максимум по
    // категории (не сумма), категория эвазиона ограничена 25 (иначе FP на играх
    // с античитом, где IsDebuggerPresent/тайминги — норма).
    static void ApplyImportChains(ScanResult res, HashSet<string> imports, string allText) {
        var norm = new HashSet<string>();
        foreach (var s in imports) norm.Add(NormApi(s));
        var best = new Dictionary<string, (int w, ChainRule r)>();
        foreach (var chain in CHAIN_RULES) {
            bool impOk = chain.ImportGroups.Length == 0;
            foreach (var grp in chain.ImportGroups) {
                bool any = false;
                foreach (var p in grp) if (norm.Contains(p)) { any = true; break; }
                if (!any) { impOk = false; break; }
            }
            if (!impOk) continue;
            if (chain.CtxGroups.Length > 0) {
                int totalHits = 0;
                bool allGrpOk = true;
                foreach (var grp in chain.CtxGroups) {
                    int g = 0;
                    foreach (var s in grp)
                        if (allText.IndexOf(s, StringComparison.OrdinalIgnoreCase) >= 0) g++;
                    if (g == 0) allGrpOk = false;
                    totalHits += g;
                }
                if (!allGrpOk || totalHits < chain.CtxMinHits) continue;
            }
            if (!best.TryGetValue(chain.Category, out var cur) || chain.Weight > cur.w)
                best[chain.Category] = (chain.Weight, chain);
        }
        foreach (var (cat, (w, r)) in best) {
            int finalW = cat == "evasion" ? Math.Min(w, 25) : w;
            Add(res, cat, "цепочка импортов: " + r.Name + " (" + r.Id + ")", finalW, "chain_" + r.Id, r.Id);
        }
    }

