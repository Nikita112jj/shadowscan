    // Извлечение вшитого ресурса в папку exe (если файла там ещё нет)
    static bool TryExtractResource(string name, out string path)
    {
        path = null;
        try
        {
            string dest = Path.Combine(AppContext.BaseDirectory, name);
            if (File.Exists(dest)) { path = dest; return true; }
            var asm = System.Reflection.Assembly.GetExecutingAssembly();
            using var s = asm.GetManifestResourceStream(name);
            if (s == null) return false;
            using var f = File.Create(dest);
            s.CopyTo(f);
            path = dest;
            return true;
        }
        catch { return false; }
    }

