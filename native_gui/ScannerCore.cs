        if (ContainsCallDelta(d))
            Add(res, "obfuscated", "call-delta с pop (PIC-код/шеллкод)", 20, "call_delta", res.File);
    }

    static bool ContainsCallDelta(byte[] d) {
        int limit = Math.Min(d.Length, 16 * 1024 * 1024);
        for (int i = 0; i + 6 <= limit; i++) {
            if (d[i] == 0xE8 && d[i+1] == 0x00 && d[i+2] == 0x00 && d[i+3] == 0x00 && d[i+4] == 0x00) {
                byte next = d[i + 5];
                if (next == 0x58 || next == 0x5B || next == 0x5D) return true;
            }
        }
        return false;
    }

    static bool ContainsAscii(byte[] d, string s) {
        var pat = Encoding.ASCII.GetBytes(s);
        if (pat.Length == 0 || d.Length < pat.Length) return false;
        int limit = Math.Min(d.Length, 8 * 1024 * 1024);
        int last = limit - pat.Length;
        for (int i = 0; i <= last; i++) {
            if (d[i] != pat[0]) continue;
            bool ok = true;
            for (int j = 1; j < pat.Length; j++) if (d[i + j] != pat[j]) { ok = false; break; }
            if (ok) return true;
        }
        return false;
    }

    static bool ContainsPattern(byte[] d, byte[] pat) {
        if (pat.Length == 0 || d.Length < pat.Length) return false;
        int limit = Math.Min(d.Length, 16 * 1024 * 1024);
        int last = limit - pat.Length;
        for (int i = 0; i <= last; i++) {
            if (d[i] != pat[0]) continue;
            bool ok = true;
            for (int j = 1; j < pat.Length; j++) if (d[i + j] != pat[j]) { ok = false; break; }
            if (ok) return true;
        }
        return false;
    }

