                            item.TryGetProperty("note", out var nt) ? nt.GetString() ?? "" : ""
                        ));
                    } catch { }
                }
            }
        } catch { /* внешние сигнатуры опциональны */ }
    }

    // Rust-движок shadow_engine.exe (если собран и лежит рядом): независимый
    // эвристический скор 0..100 на каждый файл. Возвращает путь -> score.
    // Без движка возвращает null — yara работает как раньше.
    static Dictionary<string, int> RunRustEngine(List<ScanResult> targets)
    {
        try
        {
            string exe = Path.Combine(AppContext.BaseDirectory, "shadow_engine.exe");
            if (!File.Exists(exe)) return null;
            if (targets.Count == 0) return null;
            // максимум 200 файлов за запуск (батч)
            var batch = targets.Count > 200 ? targets.GetRange(0, 200) : targets;
            var psi = new System.Diagnostics.ProcessStartInfo
            {
                FileName = exe,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true,
                StandardOutputEncoding = Encoding.UTF8,
            };
            foreach (var r in batch) psi.ArgumentList.Add(r.File);
            using var proc = System.Diagnostics.Process.Start(psi);
            if (proc == null) return null;
            string stdout = null;
            using (var outR = proc.StandardOutput.ReadToEndAsync())
            using (var errR = proc.StandardError.ReadToEndAsync())
            {
                if (!proc.WaitForExit(30_000)) { try { proc.Kill(); } catch { } return null; }
                stdout = outR.Result;
            }
            if (proc.ExitCode != 0 || string.IsNullOrWhiteSpace(stdout)) return null;
            var result = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
            using var doc = JsonDocument.Parse(stdout);
            if (doc.RootElement.ValueKind != JsonValueKind.Array) return null;
            foreach (var item in doc.RootElement.EnumerateArray())
            {
                try
                {
                    string p = item.TryGetProperty("file", out var fp) ? fp.GetString() : null;
                    int sc = item.TryGetProperty("score", out var sp) ? sp.GetInt32() : 0;
                    if (p != null) result[Path.GetFullPath(p)] = sc;
                }
                catch { }
            }
            return result;
        }
        catch { return null; }
    }

    static void CheckMagic(ScanResult res, byte[] data) {
        foreach (var (hex, offset, name, category, note) in _magicCache) {
            if (hex.Length < 2 || offset < 0 || offset + hex.Length / 2 > data.Length) continue;
            bool match = true;
            for (int i = 0; i < hex.Length; i += 2) {
                byte b = Convert.ToByte(hex.Substring(i, 2), 16);
                if (data[offset + i / 2] != b) { match = false; break; }
            }
            if (match && res.Type != "pe" && res.Type != "zip") {
                // уже известные форматы не дублируем; новый тип — уточняем
                if (hex.StartsWith("4D5A")) res.Type = "pe";
                else if (hex.StartsWith("504B")) res.Type = "zip";
            }
        }
    }

