    static void CheckVmProtection(ScanResult res, byte[] d, HashSet<string> imports) {
        string[] vmStrings = { "VMProtect", "Themida", "WinLicense", "Enigma Protector",
            "Code Virtualizer", "Oreans", "Denuvo", "IsThemidaProtected", "VMProtectBegin" };
