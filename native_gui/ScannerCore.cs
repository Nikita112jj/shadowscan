    // ============ Статический деобфускатор скриптов v2 ============
    // Снимает слои: chr-массивы -> hex-эскейпы -> base64 (std/urlsafe) ->
    // hex-литералы -> byte-массивы -> XOR (1- и N-байтовый, перебор/по ключу) ->
    // реверс строк -> ROT-сдвиги -> gzip/zlib/brotli. Каждый слой подтверждается
    // читаемостью результата (Readability). Деобфусцированный текст прогоняется
    // через правила повторно — детект обфусцированных зловредов без запуска кода.
    // Бюджет времени всего деобфускатора: патологический вход (много b64-блобов,
    // XOR-брутфорс) не должен держать скан секунды.
    static readonly System.Diagnostics.Stopwatch DeobfClock = System.Diagnostics.Stopwatch.StartNew();
    static long _deobfBudgetMs = 0;

    static string ScriptDeobfuscator(string input, int depth) {
        if (depth >= 6 || string.IsNullOrEmpty(input) || input.Length < 24) return input;
        // бюджет 5 секунд на весь деобфускатор процесса (грубо, но надёжно)
        if (_deobfBudgetMs > 5000) return input;
        bool changed = false;

        input = DecodeCharArrays(input, ref changed);
        input = DecodeInlineHexEscapes(input, ref changed);
        input = DecodeBase64Blobs(input, ref changed);
        input = DecodeHexLiterals(input, ref changed);
        input = DecodeByteArrayLiterals(input, ref changed);
        input = DecodeXorPayloads(input, ref changed);
        input = DecodeReversedStrings(input, ref changed);
        input = DecodeRotShifts(input, ref changed);

        _deobfBudgetMs = DeobfClock.ElapsedMilliseconds;
        if (changed) return ScriptDeobfuscator(input, depth + 1);
        return input;
    }

    // Читаемость 0..100: печатные ASCII + пробелы/переводы строк (FLOSS-подход).
    // Порог 55-60: результат слоя должен быть осмысленным текстом, а не мусором.
    static double Readability(byte[] b) {
        if (b == null || b.Length < 8) return 0;
        int print = 0, spaces = 0;
        for (int i = 0; i < b.Length; i++) {
            byte c = b[i];
            if (c == 9 || c == 10 || c == 13 || (c >= 32 && c < 127)) print++;
            if (c == 0x20 || c == 0x0A || c == 0x0D || c == 0x09) spaces++;
        }
        double pr = (double)print / b.Length;
        double sp = (double)spaces / b.Length;
        return pr * 70 + Math.Min(sp * 6, 30);
    }
    static double Readability(string s) {
        if (string.IsNullOrEmpty(s)) return 0;
        int n = Math.Min(s.Length, 8000);
        var bytes = new byte[n * 2]; // UTF-8 максимум 2 байта на символ для диапазона ASCII/кириллицы
        int len = 0;
        for (int i = 0; i < n; i++) {
            char c = s[i];
            if (c < 0x80) bytes[len++] = (byte)c;
            else if (c < 0x800) { bytes[len++] = (byte)(0xC0 | (c >> 6)); bytes[len++] = (byte)(0x80 | (c & 0x3F)); }
            else { bytes[len++] = 0x3F; } // сэмпл — достаточно приближения
        }
        return Readability(bytes.AsSpan(0, len).ToArray());
    }

